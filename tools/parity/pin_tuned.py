#!/usr/bin/env python3
"""Generate parity/rust_tuned_pins.json, the pins for the Rust-tuned overlay.

One-off tool, not run in CI. It sweeps every parity script through the same
comparisons as `check.py` (live oracle, wide oracle, GameSession and the three
save round trips), using only the original entries in
`parity/expected_divergences.json` as the allowlist. Whatever still differs is
where the overlay moves Rust from Python. Each such difference becomes one
exact leaf pin that names both values, checked against its own comparison.

The closed list of scripts, the entries and the paths come from the sweep, not
from a hand-kept list. The tool writes nothing when a difference cannot be
pinned within the rules: a list or object path, a wildcard, a value that is the
same on both sides, or an original pin that moved. It does not decide why a
difference exists. That proof is the `python-base` run in CI: with the overlay
compiled out and these pins unread, every script must match.

`expected_divergences.json` is never written. With `--label-goldens` the tool
adds the `_source` and `_note` lines to unlabelled goldens whose narrow
snapshot now diverges; the snapshot bytes of a golden are never touched.

Usage (after `cargo build -p portlight-cli`, with the Python game on PYTHONPATH):

    PYTHONPATH=vendor/portlight/src python3 tools/parity/pin_tuned.py --label-goldens
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import check  # noqa: E402

CHECK_ORDER = ("oracle", "oracle_wide", "gamesession") + check.ROUNDTRIP_CHECKS
OVERLAY = os.path.join(check.ROOT, "crates", "portlight-sim", "data", "tuned_overlay.json")
PYTHON_SOURCE = "the Python game at the pinned commit (captain templates unchanged)"
RUST_SOURCE = "crates/portlight-sim/data/tuned_overlay.json applied in content()"
GOLDEN_NOTE = (
    "Python oracle snapshot. Rust differs on the pinned paths in "
    "rust_tuned_pins.json (Rust-tuned)."
)
FILE_NOTE = (
    "Pins for the Rust-tuned overlay (crates/portlight-sim/data/tuned_overlay.json). "
    "Generated by tools/parity/pin_tuned.py from a sweep of every parity script; never "
    "edited by hand. Each entry is category rust-tuned, names its check as tuned_<check> (so no pair is in both files) and pins exact leaf paths with the "
    "Python value and the Rust value of one comparison: oracle (narrow snapshot), "
    "oracle_wide (wide-only keys such as the contract board), gamesession, roundtrip "
    "(Rust load of the Python save against Rust load of the Rust save), roundtrip_rust_save "
    "(Rust's save, loaded by Python and by Rust) and roundtrip_python_save (Python's save, "
    "loaded by Python and by Rust). A path whose two values are equal is refused. "
    "The Python game at the pinned commit does not know the overlay. A build with the "
    "python-base feature compiles the overlay out and does not read this file, and the "
    "oracle job runs it against every script with only the entries in "
    "expected_divergences.json. The same (script, check) pair is never in both files. "
    "Old saves reprice on load to the tuned values."
)


def natural(path: str):
    return [int(tok) if tok.isdigit() else tok for tok in re.split(r"(\d+)", path)]


def sweep_one(name: str):
    """(name, {check: (errors, left, right)}) for one script, tuned allowlist off."""
    script_path = os.path.join(check.SCRIPTS, name)
    out = {}
    with tempfile.TemporaryDirectory(prefix=f"pl-pin-{name.replace('.txt', '')}-") as save_root:
        rust = check.run_rust(script_path, os.path.join(save_root, "rust"))
        oracle = check.run_oracle(script_path, os.path.join(save_root, "oracle"))
        narrow_errors, wide_errors = check.split_wide(check.close(oracle, rust, "$"))
        out["oracle"] = (narrow_errors, oracle, rust)
        out["oracle_wide"] = (wide_errors, oracle, rust)
        session = check.run_session(script_path, os.path.join(save_root, "session"))
        if session is not None:
            session_view = check.without_log(session)
            rust_view = check.without_log(rust)
            out["gamesession"] = (check.close(session_view, rust_view, "$"), session_view, rust_view)
        if check.has_session(rust):
            out.update(check.roundtrip_compare(name, script_path))
    return name, out


def pin_value(value):
    if value is check._MISSING:
        return {"$missing": True}
    return value


def build_specs(label: str, errors: list[str], left, right) -> tuple[list[dict], list[str]]:
    """Exact leaf pins for the errors of one comparison, and what could not be pinned."""
    leaves: dict[str, None] = {}
    for line in errors:
        leaves[check.error_path(line)] = None
    specs: list[dict] = []
    problems: list[str] = []
    for path in sorted(leaves, key=natural):
        if check.pattern_error(path):
            problems.append(f"{label} wildcard path {path}")
            continue
        py = check.lookup(left, path)
        rs = check.lookup(right, path)
        if any(isinstance(v, (dict, list)) for v in (py, rs)):
            problems.append(f"{label} difference at a list or object: {path}")
            continue
        if py is check._MISSING and rs is check._MISSING:
            problems.append(f"{label} difference with no value on either side: {path}")
            continue
        spec = {"path": path, "python": pin_value(py), "rust": pin_value(rs)}
        if spec["python"] == spec["rust"] or check.values_equal(py, spec["rust"]):
            problems.append(f"{label} python and rust values are equal at {path}")
            continue
        specs.append(spec)
    return specs, problems


def levers_for(script: str, overlay_rows: list[dict]) -> str:
    """The overlay rows that can reach this script, named with base and tuned value."""
    with open(os.path.join(check.SCRIPTS, script), encoding="utf-8") as fh:
        text = fh.read()
    match = re.search(r"^new (\w+) ", text, re.M)
    captain = match.group(1) if match else None
    parts = []
    bias: dict[str, int] = {}
    for row in overlay_rows:
        if row["path"].startswith("captains[id="):
            if captain is None or f"[id={captain}]" in row["path"]:
                parts.append(f"{row['path']} {row['base']} -> {row['tuned']}")
        else:
            for added in row["tuned"][len(row["base"]) :]:
                bias[added] = bias.get(added, 0) + 1
    if captain in bias:
        parts.append(f"contracts[*].captain_bias gains {captain} on {bias[captain]} templates")
    return "; ".join(parts) if parts else "none found for this captain"


def render(entries: list[dict]) -> str:
    """The file text: one line per pin, so a diff reads one path at a time."""
    dump = lambda value: json.dumps(value, ensure_ascii=False)  # noqa: E731
    out = ["{", f'  "note": {dump(FILE_NOTE)},', '  "entries": [']
    blocks = []
    for entry in entries:
        head = {k: v for k, v in entry.items() if k != "paths"}
        lines = [f"    {dump(head)[:-1]}, \"paths\": ["]
        lines.append(",\n".join(f"      {dump(spec)}" for spec in entry["paths"]))
        lines.append("    ]}")
        blocks.append("\n".join(lines))
    out.append(",\n".join(blocks))
    out.append("  ]")
    out.append("}")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--label-goldens", action="store_true")
    parser.add_argument("--jobs", type=int, default=4)
    parser.add_argument("--no-write", action="store_true")
    args = parser.parse_args()
    if not os.path.exists(check.rust_bin()):
        raise SystemExit(f"missing {check.rust_bin()}; run cargo build -p portlight-cli")
    try:
        import portlight  # noqa: F401
    except ImportError as exc:
        raise SystemExit(f"Python game not importable: {exc}") from exc

    untagged = check.load_divergences(base_content=True)
    with open(OVERLAY, encoding="utf-8") as fh:
        overlay_rows = json.load(fh)["rows"]
    names = check.scripts()
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        results = dict(pool.map(sweep_one, names))

    problems: list[str] = []
    tagged: list[dict] = []
    sweep_rows: list[tuple[str, str, int]] = []
    for name in names:
        for kind in CHECK_ORDER:
            if kind not in results[name]:
                continue
            errors, left, right = results[name][kind]
            known = check.listed(untagged, name, kind)
            patterns = [spec["path"] for entry in known for spec in entry["paths"]]
            allowed, unexpected, missing = check.partition(errors, patterns)
            if known and missing:
                problems.append(f"{name} [{kind}] an original pin stopped differing: {missing}")
            for entry in known:
                for spec in entry["paths"]:
                    py = check.lookup(left, spec["path"])
                    rs = check.lookup(right, spec["path"])
                    if not check.values_equal(py, spec["python"]) or not check.values_equal(
                        rs, spec["rust"]
                    ):
                        problems.append(f"{name} [{kind}] an original pin moved: {spec['path']}")
            if not unexpected:
                continue
            specs, bad = build_specs(f"{name} [{kind}]", unexpected, left, right)
            problems.extend(bad)
            if not specs:
                continue
            tagged.append(
                {
                    "script": name,
                    "check": check.TUNED_CHECK_PREFIX + kind,
                    "category": check.TUNED_CATEGORY,
                    "summary": (
                        f"Rust-tuned: {len(specs)} {kind} paths differ. Levers (base -> tuned): "
                        f"{levers_for(name, overlay_rows)}"
                    ),
                    "rust": RUST_SOURCE,
                    "python": PYTHON_SOURCE,
                    "paths": specs,
                }
            )
            sweep_rows.append((name, kind, len(specs)))
    if problems:
        print("cannot pin within the rules; nothing written:")
        for line in problems:
            print("  ", line)
        return 1

    print("script\tcheck\tpaths")
    for name, kind, count in sweep_rows:
        print(f"{name}\t{kind}\t{count}")
    scripts = sorted({row[0] for row in sweep_rows})
    print(
        f"closed list: {len(scripts)} scripts, {len(tagged)} entries, "
        f"{sum(row[2] for row in sweep_rows)} paths"
    )

    if args.no_write:
        return 0
    with open(check.TUNED_PINS, "w", encoding="utf-8") as fh:
        fh.write(render(tagged))

    if args.label_goldens:
        wanted = {row[0] for row in sweep_rows if row[1] == "oracle"}
        for name in sorted(wanted):
            path = os.path.join(check.GOLDEN, name.replace(".txt", ".json"))
            with open(path, encoding="utf-8") as fh:
                text = fh.read()
            data = json.loads(text)
            if data.get("_source") == "python-oracle":
                continue
            if not text.startswith("{\n"):
                print(f"cannot label {path}: unexpected layout")
                return 1
            label = f'  "_source": "python-oracle",\n  "_note": {json.dumps(GOLDEN_NOTE)},\n'
            with open(path, "w", encoding="utf-8") as fh:
                fh.write("{\n" + label + text[2:])
            print(f"labelled {os.path.basename(path)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
